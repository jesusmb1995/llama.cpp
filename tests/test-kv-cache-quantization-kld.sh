echo "    Mean KLD → 0 = identical to f16.  Lower is better."
echo "    Δp RMS   → 0 = no probability shift.  Lower is better."
echo "    Same top → 100% = always same top prediction as f16."
echo "    ln(PPL(Q)/PPL(base)) → 0 = same perplexity.  Positive = worse."
